String constantName(String id) {
  final words = id.split(RegExp('[^a-zA-Z0-9]+')).where((s) => s.isNotEmpty);
  if (words.isEmpty) {
    throw FormatException('ID has no identifier characters: $id');
  }
  final parts = words.toList();
  var name = parts.first.replaceFirstMapped(
    RegExp(r'^[A-Z]+(?=[A-Z][a-z]|[0-9]|$)|^[A-Z]'),
    (match) => match[0]!.toLowerCase(),
  );
  for (final word in parts.skip(1)) {
    name += word[0].toUpperCase() + word.substring(1);
  }
  if (RegExp('^[0-9]').hasMatch(name)) name = 'id$name';
  return name;
}

Map<String, String> generateIds(Object? input) {
  if (input is! Map<String, dynamic> ||
      input.length != kinds.length ||
      !kinds.every(input.containsKey)) {
    throw const FormatException(
      'Expected exactly pokemon, move, ability, item',
    );
  }
  final outputs = <String, String>{};
  for (final kind in kinds) {
    final ids = input[kind];
    if (ids is! List || ids.isEmpty) {
      throw FormatException('Expected non-empty ID list: $kind');
    }
    final names = <String, String>{};
    final seen = <String>{};
    final type = '${kind[0].toUpperCase()}${kind.substring(1)}Id';
    final buffer = StringBuffer(
      '// Generated by tool/generate_ids.dart. Do not edit.\n'
      "part of '../value_objects.dart';\n\n"
      'final class $type extends Value<String> {\n'
      '  const $type._(super.value) : super._();\n'
      '  static Validation<$type> create(String value) => value.isNotEmpty\n'
      '      ? Valid($type._(value))\n'
      "      : Invalid([const ValidationError('value', ValidationCode.required)]);\n\n",
    );
    for (final id in ids) {
      if (id is! String || id.isEmpty || !seen.add(id)) {
        throw FormatException('Empty, invalid, or duplicate ID: $kind/$id');
      }
      final name = nameOverrides['$kind/$id'] ?? constantName(id);
      if (reserved.contains(name) ||
          names.containsKey(name) ||
          !RegExp(r'^[a-zA-Z][a-zA-Z0-9]*$').hasMatch(name)) {
        throw FormatException('Unresolved name collision: $kind/$id -> $name');
      }
      names[name] = id;
      buffer.writeln(
        '  static const $name = $type._(${jsonEncode(id).replaceAll(r'$', r'\$')});',
      );
    }
    buffer.writeln('\n  static const knownValues = <$type>[');
    for (final name in names.keys) {
      buffer.writeln('    $name,');
    }
    buffer.writeln('  ];\n}');
    outputs['lib/src/models/value_objects/${kind}_id.dart'] = buffer.toString();
  }
  return outputs;
}

void main(List<String> args) {
  if (args.any((a) => a != '--check')) {
    stderr.writeln('Usage: dart run tool/generate_ids.dart [--check]');
    exitCode = 64;
    return;
  }
  final outputs = generateIds(
    jsonDecode(File(p.join('data', 'known_ids.json')).readAsStringSync()),
  );
  // Use the SDK formatter so --check compares the committed representation.
  final temp = Directory.systemTemp.createTempSync('known-ids-');
  try {
    for (final entry in outputs.entries) {
      final file = File(p.join(temp.path, p.posix.basename(entry.key)))
        ..writeAsStringSync(entry.value);
      final format = Process.runSync(Platform.resolvedExecutable, [
        'format',
        file.path,
      ]);
      if (format.exitCode != 0) throw StateError('${format.stderr}');
      final contents = file.readAsStringSync();
      final target = File(p.joinAll(p.posix.split(entry.key)));
      if (args.contains('--check')) {
        if (!target.existsSync() || target.readAsStringSync() != contents) {
          stderr.writeln('Generated ID file is stale: ${entry.key}');
          exitCode = 1;
        }
      } else {
        target.writeAsStringSync(contents);
      }
    }
  } finally {
    temp.deleteSync(recursive: true);
  }
}
